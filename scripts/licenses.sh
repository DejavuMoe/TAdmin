#!/usr/bin/env bash
set -euo pipefail

# Run from the repository root on Linux after updating Go dependencies.
output=${1:-THIRD_PARTY_NOTICES.txt}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
GOBIN="$work/bin" go install github.com/google/go-licenses/v2@v2.0.1
for arch in amd64 arm64; do
  if ! GOOS=linux GOARCH="$arch" "$work/bin/go-licenses" save ./cmd/tadmin \
    --ignore=tadmin,github.com/segmentio/asm --save_path "$work/$arch" >"$work/$arch.log" 2>&1; then
    cat "$work/$arch.log" >&2
    exit 1
  fi
done
# The scanner does not recognize MIT-0 or the embedded Go font's own notice.
mkdir -p "$work/amd64/github.com/segmentio/asm" "$work/amd64/golang.org/x/image/font/gofont" "$work/amd64/Go"
cp "$(go list -m -f '{{.Dir}}' github.com/segmentio/asm)/LICENSE" "$work/amd64/github.com/segmentio/asm/LICENSE"
cp "$(go list -m -f '{{.Dir}}' golang.org/x/image)/font/gofont/ttfs/README" "$work/amd64/golang.org/x/image/font/gofont/LICENSE"
cp "$(go env GOROOT)/LICENSE" "$work/amd64/Go/LICENSE"
python3 - "$work" "$output" <<'PY'
from pathlib import Path
import sys

work, output = map(Path, sys.argv[1:])
notices = {}
for arch in ("amd64", "arm64"):
    for path in (work / arch).rglob("*"):
        if path.is_file():
            name = path.relative_to(work / arch).as_posix()
            body = path.read_text(encoding="utf-8").strip()
            assert body, f"Empty license: {name}"
            assert name not in notices or notices[name] == body, f"Conflicting license: {name}"
            notices[name] = body
assert len(notices) >= 3
text = "Third-party notices for TAdmin Linux AMD64 and ARM64 binaries.\n"
text += "Generated by scripts/licenses.sh; TAdmin itself is covered by LICENSE.\n"
for name, body in sorted(notices.items()):
    text += f"\n{'=' * 72}\n{name}\n{'=' * 72}\n\n{body}\n"
output.write_text(text, encoding="utf-8", newline="\n")
print(f"Collected {len(notices)} license and notice files: {output}")
PY
